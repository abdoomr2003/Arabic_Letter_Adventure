const TABLES: Record<Lang, Record<string, Entry>> = { ar: AR, en: EN };

export function translate(lang: Lang, key: string, vars: Record<string, string | number> = {}): string {
  const entry = TABLES[lang][key] ?? TABLES.en[key];
  if (entry === undefined) return key;
  return typeof entry === 'function' ? entry(vars) : entry;
}

export function tMsg(lang: Lang, msg: Msg | undefined): string {
  if (!msg) return '';
  return translate(lang, msg.key, msg.vars);
}

export function msg(key: string, vars?: Record<string, string | number>): Msg {
  return { key, vars };
}

/** Human-readable dots description, used for teaching feedback. */
export function dotsKey(count: number, place: 'above' | 'below' | 'none'): string | null {
  if (count === 0 || place === 'none') return null;
  return `dots.${place}${count}`;
}
